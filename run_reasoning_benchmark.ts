async function runOneExtraction(
  filePath: string,
  reasoningLevel: ReasoningLevel
): Promise<{ parsed: any; perf: PerfMetrics; rawError?: string }> {
  const buffer = fs.readFileSync(filePath);
  const fileName = path.basename(filePath);

  // Upload to OpenAI
  const fileObj = await toFile(buffer, fileName, { type: 'application/pdf' });
  const uploadStart = performance.now();
  const uploaded = await openai.files.create({ file: fileObj, purpose: 'user_data' as any });
  const uploadTime = (performance.now() - uploadStart) / 1000;

  const requestStart = performance.now();
  let firstTokenTime: number | null = null;
  let responseText = '';

  try {
    const stream = await (openai as any).responses.create({
      model: 'gpt-5.6-luna',
      input: [{
        role: 'user',
        content: [
          { type: 'input_file', file_id: uploaded.id },
          { type: 'input_text', text: PROMPT }
        ]
      }],
      text: {
        format: {
          type: 'json_schema',
          name: 'esol_paper_schema',
          strict: true,
          schema: SCHEMA
        }
      },
      reasoning: { effort: reasoningLevel },
      stream: true
    });

    let usageData: any = null;

    for await (const chunk of stream as any) {
      if (!firstTokenTime) {
        firstTokenTime = performance.now();
      }
      if (chunk.type === 'response.completed') {
        usageData = chunk.response?.usage;
      }
      const text = chunk.output_text || chunk.text || chunk.choices?.[0]?.delta?.content || '';
      responseText += text;
    }

    const endTime = performance.now();

    const perf: PerfMetrics = {
      uploadTime: Number(uploadTime.toFixed(2)),
      ttft: firstTokenTime ? Number(((firstTokenTime - requestStart) / 1000).toFixed(2)) : -1,
      generationTime: firstTokenTime ? Number(((endTime - firstTokenTime) / 1000).toFixed(2)) : -1,
      totalInference: Number(((endTime - requestStart) / 1000).toFixed(2)),
      totalApi: Number(((endTime - requestStart + uploadTime * 1000) / 1000).toFixed(2)),
      inputTokens: usageData?.input_tokens ?? 0,
      outputTokens: usageData?.output_tokens ?? 0,
      reasoningTokens: usageData?.output_tokens_details?.reasoning_tokens ?? 0,
    };

    let parsed: any = null;
    try {
      parsed = JSON.parse(responseText);
    } catch {
      return { parsed: null, perf, rawError: 'JSON parse failed: ' + responseText.slice(0, 200) };
    }

    return { parsed, perf };
  } finally {
    try { await openai.files.delete(uploaded.id); } catch {}
  }
}

function evaluateAccuracy(parsed: any, spec: typeof PDF_TEST_SET[0]): AccuracyMetrics {
  if (!parsed) {
    return {
      docTypeCorrect: false, sectionCountCorrect: false, questionCountCorrect: false,
      questionCountExtracted: 0, sectionCountExtracted: 0,
      answerStateCorrectRate: 0, printedAnswerDetectionRate: 0,
      contextDetected: false, contextBoundaryScore: null, contextCoordsDiverse: null,
      coordsValid: 0, highConfidenceAnswerRate: 0, unknownAnswerRate: 0,
      hasDuplicateQuestions: false, errorCount: 1
    };
  }

  const questions: any[] = parsed.questions || [];
  const sections: any[] = parsed.sections || [];

  // Doc type
  const docTypeCorrect = spec.expectedDocType
    ? parsed.documentType === spec.expectedDocType
    : null;

  // Section count
  const sectionCountExtracted = sections.length;
  const sectionCountCorrect = spec.expectedSections !== null
    ? sectionCountExtracted === spec.expectedSections
    : null;

  // Question count
  const questionCountExtracted = questions.filter((q: any) => q.type !== 'INSTRUCTION').length;
  const questionCountCorrect = spec.expectedQuestions !== null
    ? questionCountExtracted === spec.expectedQuestions
    : null;

  // AnswerState accuracy (for hasPrintedAnswers papers, most should be PRINTED)
  let answerStateCorrectRate = 0;
  let printedAnswerDetectionRate = 0;
  const realQuestions = questions.filter((q: any) => q.type !== 'INSTRUCTION');

  if (realQuestions.length > 0) {
    if (spec.hasPrintedAnswers) {
      const printedCount = realQuestions.filter((q: any) => q.answerState === 'PRINTED').length;
      printedAnswerDetectionRate = printedCount / realQuestions.length;
      answerStateCorrectRate = printedAnswerDetectionRate;
    } else {
      // For candidate/sample papers, most answers should be AI_SOLVED (not PRINTED, not UNKNOWN)
      const correctCount = realQuestions.filter((q: any) =>
        q.answerState === 'AI_SOLVED' || q.answerState === 'UNKNOWN'
      ).length;
      answerStateCorrectRate = correctCount / realQuestions.length;
    }
  }

  // Context regions
  const contextDetected = sections.some((s: any) => s.contextRegions?.length > 0);
  let coordsValidCount = 0;
  let coordsTotal = 0;
  const allDimensions: number[] = [];

  for (const section of sections) {
    for (const cr of (section.contextRegions || [])) {
      coordsTotal++;
      const valid =
        typeof cr.left === 'number' && typeof cr.top === 'number' &&
        typeof cr.right === 'number' && typeof cr.bottom === 'number' &&
        cr.left >= 0 && cr.top >= 0 && cr.right <= 1 && cr.bottom <= 1 &&
        cr.left < cr.right && cr.top < cr.bottom;
      if (valid) coordsValidCount++;
      allDimensions.push(cr.bottom - cr.top);
    }
  }

  const coordsValid = coordsTotal > 0 ? coordsValidCount / coordsTotal : 0;

  // Check if different sections got different dimensions (vs. fixed-size templating)
  let contextCoordsDiverse: boolean | null = null;
  if (allDimensions.length >= 2) {
    const min = Math.min(...allDimensions);
    const max = Math.max(...allDimensions);
    contextCoordsDiverse = (max - min) > 0.05; // at least 5% height difference across sections
  }

  // High confidence answers
  const highConfidenceAnswerRate = realQuestions.length > 0
    ? realQuestions.filter((q: any) => q.confidence === 'HIGH').length / realQuestions.length
    : 0;

  // Unknown rate (hallucination guard proxy)
  const unknownAnswerRate = realQuestions.length > 0
    ? realQuestions.filter((q: any) => q.answerState === 'UNKNOWN').length / realQuestions.length
    : 0;

  // Duplicate detection
  const contents = realQuestions.map((q: any) => (q.content || '').trim().toLowerCase());
  const uniqueContents = new Set(contents);
  const hasDuplicateQuestions = uniqueContents.size < contents.length;

  return {
    docTypeCorrect,
    sectionCountCorrect,
    questionCountCorrect,
    questionCountExtracted,
    sectionCountExtracted,
    answerStateCorrectRate: Number(answerStateCorrectRate.toFixed(3)),
    printedAnswerDetectionRate: Number(printedAnswerDetectionRate.toFixed(3)),
    contextDetected,
    contextBoundaryScore: null, // set manually after visual review
    contextCoordsDiverse,
    coordsValid: Number(coordsValid.toFixed(3)),
    highConfidenceAnswerRate: Number(highConfidenceAnswerRate.toFixed(3)),
    unknownAnswerRate: Number(unknownAnswerRate.toFixed(3)),
    hasDuplicateQuestions,
    errorCount: 0,
  };
}

