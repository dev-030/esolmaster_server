interface PerfMetrics {
  uploadTime: number;
  ttft: number;
  generationTime: number;
  totalInference: number;
  totalApi: number;
  inputTokens: number;
  outputTokens: number;
  reasoningTokens: number;
}

interface AccuracyMetrics {
  docTypeCorrect: boolean | null;
  sectionCountCorrect: boolean | null;
  questionCountCorrect: boolean | null;
  questionCountExtracted: number;
  sectionCountExtracted: number;
  answerStateCorrectRate: number;   // % of questions with correct answerState category
  printedAnswerDetectionRate: number; // if hasPrintedAnswers, % of Qs with PRINTED state
  contextDetected: boolean;         // at least one contextRegion found
  contextBoundaryScore: number | null; // 0-3 manual sanity checks (set post-run)
  contextCoordsDiverse: boolean | null; // sections have different dimensions
  coordsValid: number;              // % of contextRegions with valid 0-1 bounds
  highConfidenceAnswerRate: number; // % of answers with HIGH confidence
  unknownAnswerRate: number;        // % with UNKNOWN (hallucination avoidance proxy)
  hasDuplicateQuestions: boolean;
  errorCount: number;
}

interface RunResult {
  reasoningLevel: ReasoningLevel;
  pdfLabel: string;
  perf: PerfMetrics;
  accuracy: AccuracyMetrics;
  parsed: any;
  rawError?: string;
}

